local H = require("helpers")
local ws = require("cueline.ws")
local describe, it, eq = H.describe, H.it, H.eq

local function hex(s)
  return (s:gsub(".", function(c)
    return ("%02x"):format(c:byte())
  end))
end

describe("ws framing", function()
  local mask = string.char(0x37, 0xfa, 0x21, 0x3d)
  it("masks like RFC 6455 section 5.7", function()
    eq("818537fa213d7f9f4d5158", hex(ws.encode(ws.OP.text, "Hello", mask)))
  end)
  it("encodes unmasked server frames", function()
    eq("810548656c6c6f", hex(ws.encode(ws.OP.text, "Hello", false)))
  end)
  it("uses 16-bit and 64-bit lengths", function()
    local p16 = string.rep("a", 300)
    local f16 = ws.encode(ws.OP.binary, p16, false)
    eq("827e012c", hex(f16:sub(1, 4)))
    local p64 = string.rep("b", 70000)
    local f64 = ws.encode(ws.OP.binary, p64, false)
    eq("827f0000000000011170", hex(f64:sub(1, 10)))
  end)
  it("decodes masked and unmasked frames, split at any byte", function()
    local payload = string.rep("xyz", 50000)
    local stream = ws.encode(ws.OP.text, "Hello", mask) .. ws.encode(ws.OP.binary, payload, false)
    local d, out = ws.decoder(), {}
    for i = 1, #stream, 997 do
      vim.list_extend(out, d.feed(stream:sub(i, i + 996)))
    end
    eq(2, #out)
    eq({ ws.OP.text, "Hello" }, { out[1].opcode, out[1].payload })
    eq(#payload, #out[2].payload)
    eq(payload, out[2].payload)
  end)
  it("reassembles fragmented messages around a control frame", function()
    local first = string.char(0x01, 3) .. "abc" -- text, FIN clear
    local ping = string.char(0x89, 1) .. "p"
    local last = string.char(0x80, 3) .. "def" -- continuation, FIN
    local out = ws.decoder().feed(first .. ping .. last)
    eq(2, #out)
    eq({ ws.OP.ping, "p" }, { out[1].opcode, out[1].payload })
    eq({ ws.OP.text, "abcdef" }, { out[2].opcode, out[2].payload })
  end)
  it("round-trips utf-8", function()
    local s = "naïve café — ▶ 字幕"
    local out = ws.decoder().feed(ws.encode(ws.OP.text, s))
    eq(s, out[1].payload)
  end)
end)

describe("ws handshake", function()
  it("builds an upgrade request", function()
    local req = ws.handshake_request("127.0.0.1", 10427, "abc==")
    H.truthy(req:find("GET / HTTP/1.1\r\n", 1, true))
    H.truthy(req:find("Sec-WebSocket-Key: abc==\r\n", 1, true))
    H.truthy(req:sub(-4) == "\r\n\r\n")
  end)
  it("waits for the full response and returns leftover bytes", function()
    eq(nil, ws.parse_handshake("HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket"))
    local ok, rest = ws.parse_handshake("HTTP/1.1 101 Switching Protocols\r\n\r\n\129\1x")
    eq(true, ok)
    eq("\129\1x", rest)
    eq(false, (ws.parse_handshake("HTTP/1.1 400 Bad Request\r\n\r\n")))
  end)
end)
